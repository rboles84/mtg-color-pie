#!/usr/bin/env python3
"""
Inline the runtime projection into the single-file app.

    python tools/inline_runtime.py --data data/ --html vox-color/color-wheel.html

The app is opened from file:// with no build step, so fetch() cannot load a
sibling JSON: browsers refuse cross-origin reads on the file scheme. The data
therefore has to live inside the document. It is GENERATED between markers, so
it is still not hand-maintained -- editing it by hand is the thing this file
exists to prevent.

byColor and byFamily are dropped and re-derived in the page. They are pure
indexes over byMechanic, and shipping them would mean shipping the same long
keys three times.
"""
import argparse, json, pathlib, sys

BEGIN = "/* MCP-RUNTIME:BEGIN generated by tools/inline_runtime.py - do not edit */"
END   = "/* MCP-RUNTIME:END */"

ap = argparse.ArgumentParser()
ap.add_argument("--data", type=pathlib.Path, default=pathlib.Path("data"))
ap.add_argument("--html", type=pathlib.Path,
                default=pathlib.Path("vox-color/color-wheel.html"))
a = ap.parse_args()

rt = json.loads((a.data / "mechanical-color-pie.runtime.json").read_text(encoding="utf-8"))
slim = {"meta": rt["meta"], "byMechanic": rt["byMechanic"]}
blob = json.dumps(slim, separators=(",", ":"), ensure_ascii=False)
block = BEGIN + "\nconst MCP = " + blob + ";\n" + END

html = a.html.read_text(encoding="utf-8")
if BEGIN in html:
    i = html.index(BEGIN); j = html.index(END) + len(END)
    html = html[:i] + block + html[j:]
else:
    anchor = "/* ======================================================================\n   IDENTITY REGISTRY"
    if anchor not in html:
        sys.exit("no marker and no anchor found; refusing to guess a location")
    html = html.replace(anchor, block + "\n\n" + anchor, 1)

a.html.write_text(html, encoding="utf-8", newline="")
print("inlined %d mechanics (%d KB of JSON) into %s"
      % (len(slim["byMechanic"]), len(blob.encode("utf-8")) // 1024, a.html.name))
